"""Generate the TGPSC AEE Civil practice seed and its answer audit from reviewed data."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'supabase/data/tgpsc_aee_civil_questions.json'
TITLE = 'TGPSC AEE Civil Exam'
DESCRIPTION = ('Unofficial practice version based on the uploaded TSPSC AEE Civil Paper II, '
               '22 January 2023 (paper code 22122). 150 questions: 108 transcribed with notation/wording normalization '
               'and 42 explicitly labeled concept adaptations or corrections. Answers are independently derived, '
               'not an official answer key. Practice scoring: +2 correct, 0 wrong or unanswered; 150-minute duration. '
               'The 150-mark practice benchmark is not an official qualifying cutoff.')

def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def main():
    questions = json.loads(DATA.read_text(encoding='utf-8'))
    assert [q['number'] for q in questions] == list(range(1, 151)), 'Expected ordered source numbers 1-150'
    assert len({q['question_text'] for q in questions}) == 150, 'Duplicate question text'
    seed = []
    for q in questions:
        assert q['source_status'] in ('transcribed', 'adapted')
        assert len(q['options']) == 4 and len(set(q['options'])) == 4
        assert all(isinstance(x, str) and x.strip() for x in [q['question_text'], q['rationale'], *q['options']])
        assert q['correct_answer'] in 'ABCD' and len(q['correct_answer']) == 1
        prefix = '[Civil Engineering] ' + ('(Adapted concept question) ' if q['source_status'] == 'adapted' else '')
        seed.append(dict(display_order=q['number'], question_text=prefix + q['question_text'],
                         options=[dict(value=letter, text=text) for letter, text in zip('ABCD', q['options'])],
                         correct_answer=q['correct_answer']))
    payload = json.dumps(seed, ensure_ascii=False, indent=2)
    template = (ROOT / 'supabase/junior_engineer_2024_civil_paper_i_mock_seed.sql').read_text(encoding='utf-8')
    branch_setup = template[template.index('    SELECT id INTO v_branch_id'):template.index('    SELECT id INTO v_test_id')]
    branch_setup = branch_setup.replace('Civil engineering subjects and SSC JE practice', 'Civil engineering subjects and competitive exam practice')
    sql = f'''-- Generated by scripts/build_tgpsc_aee_civil_seed.py; edit the JSON source and regenerate.
-- Source: MockTests/tspsc civil aee.pdf, physical PDF pages 3-22 (source Q1-Q150).
-- UNOFFICIAL: independently derived keys; handwritten ticks are NOT an answer key.
-- 108 normalized transcriptions and 42 labeled adaptations. See the review document.
-- Run mock_test_setup.sql, then mock_simulation_functions.sql, then this seed.
-- Practice policy: 150 minutes; +2 correct; 0 wrong/unanswered; benchmark 150/300.
-- Repeated runs fill missing identical rows; conflicting existing content aborts atomically.
DO $seed$
DECLARE
    v_branch_id UUID;
    v_subject_id UUID;
    v_test_id UUID;
    v_question_count INT;
    v_seed JSONB := $questions$
{payload}
$questions$::JSONB;
BEGIN
    IF to_regclass('public.engineering_branches') IS NULL
       OR to_regclass('public.subjects') IS NULL
       OR to_regclass('public.mock_tests') IS NULL
       OR to_regclass('public.mock_questions') IS NULL THEN
        RAISE EXCEPTION 'Missing mock-test tables. Run supabase/mock_test_setup.sql first, then supabase/mock_simulation_functions.sql, then rerun this seed.';
    END IF;
{branch_setup}
    SELECT id INTO v_test_id FROM public.mock_tests
    WHERE title = {sql_text(TITLE)} LIMIT 1;

    IF v_test_id IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.mock_questions existing
        LEFT JOIN jsonb_to_recordset(v_seed) AS q(
            display_order INT, question_text TEXT, options JSONB, correct_answer TEXT
        ) ON q.display_order = existing.display_order
        WHERE existing.mock_test_id = v_test_id
          AND (q.display_order IS NULL
               OR existing.question_text IS DISTINCT FROM q.question_text
               OR existing.question_type IS DISTINCT FROM 'mcq'
               OR existing.options IS DISTINCT FROM q.options
               OR existing.correct_answer IS DISTINCT FROM q.correct_answer
               OR existing.marks IS DISTINCT FROM 2
               OR existing.negative_marks IS DISTINCT FROM 0)
    ) THEN
        RAISE EXCEPTION 'Existing TGPSC AEE Civil questions differ from this seed; refusing to overwrite answers or attempt history';
    END IF;

    IF v_test_id IS NULL THEN
        INSERT INTO public.mock_tests (
            title, description, exam_type, subject_id, duration_minutes,
            total_marks, passing_marks, is_published
        ) VALUES (
            {sql_text(TITLE)}, {sql_text(DESCRIPTION)},
            'OTHER', v_subject_id, 150, 300, 150, TRUE
        ) RETURNING id INTO v_test_id;
    ELSE
        UPDATE public.mock_tests SET
            description = {sql_text(DESCRIPTION)},
            exam_type = 'OTHER', subject_id = v_subject_id,
            duration_minutes = 150, total_marks = 300, passing_marks = 150,
            is_published = TRUE
        WHERE id = v_test_id;
    END IF;

    INSERT INTO public.mock_questions (
        mock_test_id, question_text, question_type, options, correct_answer,
        marks, negative_marks, display_order
    )
    SELECT v_test_id, q.question_text, 'mcq', q.options, q.correct_answer,
           2, 0, q.display_order
    FROM jsonb_to_recordset(v_seed) AS q(
        display_order INT, question_text TEXT, options JSONB, correct_answer TEXT
    )
    WHERE NOT EXISTS (
        SELECT 1 FROM public.mock_questions existing
        WHERE existing.mock_test_id = v_test_id AND existing.display_order = q.display_order
    );

    SELECT count(*) INTO v_question_count FROM public.mock_questions
    WHERE mock_test_id = v_test_id;
    IF v_question_count <> 150 OR (
        SELECT count(DISTINCT display_order) FROM public.mock_questions WHERE mock_test_id = v_test_id
    ) <> 150 THEN
        RAISE EXCEPTION 'Expected 150 uniquely ordered questions, found %', v_question_count;
    END IF;
    RAISE NOTICE 'TGPSC AEE Civil Exam ready: 150 questions, 300 marks, unofficial practice key.';
END;
$seed$;
'''
    (ROOT / 'supabase/tgpsc_aee_civil_mock_seed.sql').write_text(sql, encoding='utf-8')
    audit = ['# TGPSC AEE Civil Exam: source and answer review', '', DESCRIPTION, '',
             '## Source and use', '',
             '- Local source: `MockTests/tspsc civil aee.pdf`, 22 pages. Questions occupy physical PDF pages 3-22; printed page numbers differ.',
             '- Order and question numbers correspond to the uploaded booklet, not an internet master-booklet answer key.',
             '- Transcribed means original question content and option order retained, with spelling, notation, layout and light wording normalization. It does not mean a facsimile.',
             '- Adapted means a clarified assumption, corrected choice, text replacement for a diagram, or a similar concept question. These are labeled in the candidate interface.',
             '- No handwritten ticks were treated as authority. All keys below are unofficial derived practice answers.',
             '- This is a preparation exercise, not a declaration of current recruitment rules or official cutoffs.',
             '- Run `supabase/tgpsc_aee_civil_mock_seed.sql` in Supabase SQL Editor after `supabase/mock_test_setup.sql` and `supabase/mock_simulation_functions.sql`. No credentials or live database were used to create it.',
             '- Regenerate with `python scripts/build_tgpsc_aee_civil_seed.py` after editing the JSON source. The JSON and this document contain keys and must not be served as browser assets.',
             '', '## Supporting references checked', '',
             '- IIT Madras / NPTEL: design bond stresses reproduced from IS 456:2000: https://archive.nptel.ac.in/content/storage2/courses/105106117/pdf/7_Transmission_of_Prestress/Section7.1.pdf',
             '- Government engineering tender: assumed concrete strength deviations: https://kmda.wb.gov.in/upload_file/tender/51_SE_C-III_RB_KMDA.pdf',
             '- NPTEL: Muskingum routing: https://archive.nptel.ac.in/content/storage2/courses/105101002/modules/module5/lec3/1.7.html',
             '', '## Adaptation index', '', ', '.join('Q'+str(q['number']) for q in questions if q['source_status']=='adapted'),
             '', '## Answer reasoning', '']
    for q in questions:
        audit.extend([f"### Q{q['number']} - {q['correct_answer']} ({q['source_status']}; PDF page {q['pdf_page']})", '', q['rationale'], ''])
    (ROOT / 'supabase/data/tgpsc_aee_civil_review.md').write_text('\n'.join(audit), encoding='utf-8')
    print(f'Validated and generated {len(seed)} questions; maximum marks = {2 * len(seed)}.')

if __name__ == '__main__':
    main()
