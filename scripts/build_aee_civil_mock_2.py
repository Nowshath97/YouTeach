"""Build the original Civil Mock 2 and private answer review; no browser keys."""
import collections
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TITLE = 'TGPSC AEE Civil Mock 2'
DESCRIPTION = (
    'Original unofficial Civil-only AEE-style practice: 100 questions, 100 minutes, '
    '200 marks. Mixed order: 40 theory, 30 short numericals, 20 multiple-statement '
    'combinations and 10 matching questions. No General Studies. Choose ONE coded '
    'answer per question, including the correct combination for multiple statements '
    'and matching. Scoring: +2 correct; 0 wrong or unanswered. The 100-mark practice '
    'benchmark is not an official qualifying cutoff. Inspired by the variety of '
    'AEE/ESE objective formats; not an official paper or a claim of ESE-equivalent difficulty.'
)
KINDS = {'T': 'theory', 'N': 'short numerical', 'S': 'statement combination', 'M': 'matching'}


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    questions = []
    topic = None
    for line in (ROOT / 'supabase/data/aee_civil_mock_2_source.txt').read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        if line.startswith('@ '):
            topic = line[2:]
            continue
        fields = line.split('|')
        assert len(fields) == 9, (topic, fields)
        kind, difficulty, stem, *rest = fields
        options, key, rationale = rest[:4], rest[4], rest[5]
        assert kind in KINDS and difficulty in ('easy', 'moderate', 'hard')
        assert topic and key in 'ABCD' and len(key) == 1
        assert len(set(options)) == 4 and all(x.strip() for x in [stem, rationale, *options])
        questions.append(dict(topic=topic, kind=KINDS[kind], editorial_difficulty=difficulty,
                              question_text=stem.replace('\\n', '\n'), options=options,
                              correct_answer=key, rationale=rationale))
    assert len(questions) == 100
    assert len({q['question_text'] for q in questions}) == 100
    assert collections.Counter(q['kind'] for q in questions) == {
        'theory': 40, 'short numerical': 30, 'statement combination': 20, 'matching': 10}
    assert set(collections.Counter(q['topic'] for q in questions).values()) == {10}
    random.Random(22122026).shuffle(questions)
    # Shuffle options too, retaining every key and avoiding a predictable answer cycle.
    rng = random.Random(17102026)
    seed = []
    for number, q in enumerate(questions, 1):
        correct_text = q['options']['ABCD'.index(q['correct_answer'])]
        rng.shuffle(q['options'])
        q['correct_answer'] = 'ABCD'[q['options'].index(correct_text)]
        q['number'] = number
        seed.append(dict(display_order=number,
                         question_text='[Civil Engineering] ' + q['question_text'],
                         options=[dict(value=k, text=v) for k, v in zip('ABCD', q['options'])],
                         correct_answer=q['correct_answer']))

    # Reuse the already reviewed atomic, non-overwriting seed structure.
    template = (ROOT / 'supabase/tgpsc_aee_civil_mock_seed.sql').read_text(encoding='utf-8')
    begin, tail = template.split('$questions$::JSONB;', 1)
    _, header = begin.split('DO $seed$', 1)
    declarations = header.split('$questions$', 1)[0]
    import build_tgpsc_aee_civil_seed as original
    tail = tail.replace(quote(original.DESCRIPTION), quote(DESCRIPTION))
    tail = tail.replace('TGPSC AEE Civil Exam', TITLE)
    tail = tail.replace('Existing TGPSC AEE Civil questions', 'Existing TGPSC AEE Civil Mock 2 questions')
    tail = tail.replace('v_subject_id, 150, 300, 150, TRUE', 'v_subject_id, 100, 200, 100, TRUE')
    tail = tail.replace('duration_minutes = 150, total_marks = 300, passing_marks = 150',
                        'duration_minutes = 100, total_marks = 200, passing_marks = 100')
    tail = tail.replace('<> 150', '<> 100').replace('Expected 150 uniquely', 'Expected 100 uniquely')
    tail = tail.replace('150 questions, 300 marks', '100 questions, 200 marks')
    sql = ('-- Generated by scripts/build_aee_civil_mock_2.py. Original Civil-only questions.\n'
           '-- Run after mock_test_setup.sql and mock_simulation_functions.sql.\n'
           '-- 100 minutes; +2 correct; no negative marks. Re-imports preserve attempts.\n'
           'DO $seed$' + declarations + '$questions$\n' + json.dumps(seed, ensure_ascii=False, indent=2)
           + '\n$questions$::JSONB;' + tail)
    (ROOT / 'supabase/aee_civil_mock_2_seed.sql').write_text(sql, encoding='utf-8')
    (ROOT / 'supabase/data/aee_civil_mock_2_questions.json').write_text(
        json.dumps(questions, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    review = ['# Civil Mock 2 - editorial review and answer key', '', DESCRIPTION, '',
              '## Scope and references', '',
              '- Original authored questions; not transcriptions of the commercial solved-paper PDF.',
              '- Format reference: user-provided AEE Civil.pdf, sampled physical pages 3, 9, 19 and 29.',
              '- Several correct statements are answered through a single combination choice, not separate checkboxes.',
              '- Questions are deliberately interleaved in one Civil Engineering section; topic tags below are private.',
              '- Difficulty tags are editorial estimates, not calibrated candidate ability measurements.',
              '- 10 questions per subject; 40 theory, 30 short numericals, 20 statement combinations, 10 matching.',
              '- This mix tests breadth and common misconceptions. It is not a validated psychometric assessment.',
              '- No current code-clause thresholds or recruitment rules are assumed.',
              '- NPTEL effective stress and seepage: https://archive.nptel.ac.in/content/storage2/courses/105103097/web/chap5final/s3.htm',
              '- NPTEL critical gradient: https://archive.nptel.ac.in/content/storage2/courses/105103097/web/chap5final/s5.htm',
              '- UPSC ESE objective-paper context: https://www.upsc.gov.in/examinations/Engineering%20Services%20%28Preliminary%29%20Examination%2C%202026',
              '', '## Installation', '',
              'Run `supabase/aee_civil_mock_2_seed.sql` in Supabase SQL Editor. This creates a published test; '
              'it does not replace Mock 1. No live database was accessed by this generator. '
              'Keep source, JSON and this answer key outside public browser assets.', '', '## Answers', '']
    for q in questions:
        review.extend([f"### Q{q['number']} - {q['correct_answer']} | {q['topic']} | {q['kind']}", '',
                       q['question_text'], '',
                       *[f'{letter}. {option}' for letter, option in zip('ABCD', q['options'])], '',
                       '**Reason:** ' + q['rationale'], ''])
    (ROOT / 'supabase/data/aee_civil_mock_2_review.md').write_text('\n'.join(review), encoding='utf-8')
    print('Built 100 original Civil questions, 200 marks, 100 minutes.')
    print('Answer distribution:', dict(collections.Counter(q['correct_answer'] for q in questions)))


if __name__ == '__main__':
    main()
