# LEGACY: PDFs now appear in Previous Papers without SQL; not needed for the paper library.
"""Build three full GATE 2025 mocks using official PDFs and final answer-key facts.

No question text or diagrams are republished: the UI opens the official paper at
its mapped page. Existing options JSON stores public viewer metadata, while
correct_answer stores private, typed grading configuration.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    papers=json.loads((ROOT/'supabase/data/gate_2025_official_papers.json').read_text())
    cutoffs={'ME':35.8,'EE':25,'CE1':29.2}
    payload=[]
    for paper in papers:
        assert [q['number'] for q in paper['questions']]==list(range(1,66))
        assert sum(q['marks'] for q in paper['questions'])==100
        assert sum(q['marks'] for q in paper['questions'] if q['section']=='GA')==15
        questions=[]
        for q in paper['questions']:
            key=q['key']
            if key['kind']=='NAT':
                assert all(a<=b for a,b in key['ranges'])
            else:
                assert key['answers'] and all(a in 'ABCD' for a in key['answers'])
            viewer={'url':paper['paper_url'],'page':q['pdf_page'],'number':q['number'],
                    'response_type':q['response_type'],'marks':q['marks']}
            options=([{'value':a,'text':f'Option {a}'} for a in 'ABCD'] if q['response_type']!='NAT' else [{}])
            options[0]['paper']=viewer
            section='General Aptitude' if q['section']=='GA' else paper['branch']
            questions.append({'display_order':q['number'],
                              'question_text':f'[{section}] Answer Question {q["number"]} in the official {paper["code"]} master paper shown below.',
                              'question_type':'numerical' if q['response_type']=='NAT' else 'mcq',
                              'options':options,'correct_answer':'GATE2025:'+json.dumps(key,separators=(',',':')),
                              'marks':q['marks'],'negative_marks':round(q['marks']/3,2) if q['response_type']=='MCQ' else 0})
        desc=(f'Full GATE 2025 {paper["code"]} previous-year master paper: all 65 questions, 180 minutes, 100 marks. '
              'Original questions and diagrams are displayed from IIT Roorkee in a linked PDF viewer; no substitute questions. '
              'Final official key used for practice scoring: MCQ -1/3 of question marks for a wrong answer, MSQ exact-set scoring without partial credit, '
              'NAT accepted ranges; no negative marks for MSQ/NAT. '
              f'2025 General-category qualifying reference: {cutoffs[paper["code"]]} marks; category cutoffs differ. '
              'This is an independent practice interface, not an official GATE service. Original paper: '+paper['paper_url'])
        payload.append({'title':paper['title'],'branch':paper['branch'],'description':desc,'cutoff':cutoffs[paper['code']],'questions':questions})
    sql='''-- Generated by scripts/build_gate_2025_mock_seeds.py.
-- Run gate_2025_grading.sql first, then this file, against your EXISTING mock tables.
-- No tables are created. Source/key provenance: supabase/data/gate_2025_official_papers.json.
-- All 195 question slots use linked official papers, not invented/transcribed substitutes.
-- Subject links reuse existing exact branch-name subjects; otherwise NULL if allowed.
DO $seed$
DECLARE
    v_papers JSONB := $papers$\n'''+json.dumps(payload,indent=2)+'''
$papers$::JSONB;
    v_paper JSONB;
    v_questions JSONB;
    v_test_id UUID;
    v_subject_id UUID;
    v_count INT;
BEGIN
    IF to_regclass('public.mock_tests') IS NULL OR to_regclass('public.mock_questions') IS NULL THEN
        RAISE EXCEPTION 'Existing mock_tests and mock_questions tables are required. Inspect your schema before importing; this seed does not create tables.';
    END IF;
    IF to_regprocedure('public.evaluate_mock_response(text,text,text,numeric,numeric)') IS NULL
       OR NOT EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
                      WHERE n.nspname='public' AND p.proname='submit_mock_attempt'
                        AND p.prosrc LIKE '%public.evaluate_mock_response%') THEN
        RAISE EXCEPTION 'Run supabase/gate_2025_grading.sql before importing these papers; legacy grading cannot score MSQ/NAT ranges.';
    END IF;
    FOR v_paper IN SELECT value FROM jsonb_array_elements(v_papers) LOOP
        v_test_id := NULL;
        v_subject_id := NULL;
        v_questions := v_paper->'questions';
        -- Reuse subjects where the existing schema has compatible UUID IDs.
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema='public' AND table_name='subjects' AND column_name='id' AND udt_name='uuid') THEN
            EXECUTE 'SELECT id FROM public.subjects WHERE name = $1 LIMIT 1'
                INTO v_subject_id USING v_paper->>'branch';
        END IF;
        IF v_subject_id IS NULL AND EXISTS (
            SELECT 1 FROM information_schema.columns WHERE table_schema='public'
                AND table_name='mock_tests' AND column_name='subject_id' AND is_nullable='NO'
        ) THEN
            RAISE EXCEPTION 'No existing UUID subject named %. Map an existing subject before importing this paper.', v_paper->>'branch';
        END IF;
        SELECT count(*) INTO v_count FROM public.mock_tests WHERE title=v_paper->>'title';
        IF v_count>1 THEN RAISE EXCEPTION 'Multiple mocks share title %; resolve before importing',v_paper->>'title'; END IF;
        SELECT id INTO v_test_id FROM public.mock_tests WHERE title=v_paper->>'title' LIMIT 1;
        IF v_test_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM public.mock_questions e
            LEFT JOIN jsonb_to_recordset(v_questions) AS q(display_order INT,question_text TEXT,question_type TEXT,options JSONB,correct_answer TEXT,marks NUMERIC,negative_marks NUMERIC)
                ON e.display_order=q.display_order
            WHERE e.mock_test_id=v_test_id AND
                (q.display_order IS NULL OR e.question_text IS DISTINCT FROM q.question_text
                OR e.question_type IS DISTINCT FROM q.question_type OR e.options IS DISTINCT FROM q.options
                OR e.correct_answer IS DISTINCT FROM q.correct_answer OR e.marks IS DISTINCT FROM q.marks
                OR e.negative_marks IS DISTINCT FROM q.negative_marks)
        ) THEN RAISE EXCEPTION 'Existing questions differ for %; refusing to overwrite attempt history',v_paper->>'title'; END IF;
        IF v_test_id IS NULL THEN
            INSERT INTO public.mock_tests(title,description,exam_type,subject_id,duration_minutes,total_marks,passing_marks,is_published)
            VALUES(v_paper->>'title',v_paper->>'description','GATE',v_subject_id,180,100,(v_paper->>'cutoff')::NUMERIC,TRUE)
            RETURNING id INTO v_test_id;
        ELSE
            UPDATE public.mock_tests SET description=v_paper->>'description',is_published=TRUE,
                duration_minutes=180,total_marks=100,passing_marks=(v_paper->>'cutoff')::NUMERIC
            WHERE id=v_test_id;
        END IF;
        INSERT INTO public.mock_questions(mock_test_id,question_text,question_type,options,correct_answer,marks,negative_marks,display_order)
        SELECT v_test_id,q.question_text,q.question_type,q.options,q.correct_answer,q.marks,q.negative_marks,q.display_order
        FROM jsonb_to_recordset(v_questions) AS q(display_order INT,question_text TEXT,question_type TEXT,options JSONB,correct_answer TEXT,marks NUMERIC,negative_marks NUMERIC)
        WHERE NOT EXISTS(SELECT 1 FROM public.mock_questions e WHERE e.mock_test_id=v_test_id AND e.display_order=q.display_order);
        SELECT count(*) INTO v_count FROM public.mock_questions WHERE mock_test_id=v_test_id;
        IF v_count<>65 OR (SELECT sum(marks) FROM public.mock_questions WHERE mock_test_id=v_test_id)<>100 THEN
            RAISE EXCEPTION 'Expected 65 questions/100 marks for %',v_paper->>'title';
        END IF;
    END LOOP;
END;
$seed$;
'''
    (ROOT/'supabase/gate_2025_previous_year_mock_seed.sql').write_text(sql,encoding='utf-8')
    print('Generated 3 full previous-year mocks: 195 question slots, 300 total marks.')

if __name__=='__main__': main()
