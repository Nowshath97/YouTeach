cases = []
def check(number, result, choices):
    nearest = min(range(4), key=lambda i: abs(choices[i] - result))
    assert q[number]['correct_answer'] == 'ABCD'[nearest], (number, result, choices, q[number]['correct_answer'])
    cases.append(number)

